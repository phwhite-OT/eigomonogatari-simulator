import { readdir, writeFile } from "node:fs/promises";
import { extname, resolve } from "node:path";

import { CHARACTER_CATALOG } from "../src/data/character-catalog.js";

const projectRoot = resolve(import.meta.dirname, "..");
const supportedExtensions = new Set([".avif", ".jpg", ".jpeg", ".png", ".webp"]);

function readArgument(name, fallback) {
  const prefix = `--${name}=`;
  const argument = process.argv.slice(2).find((value) => value.startsWith(prefix));
  return argument ? argument.slice(prefix.length) : fallback;
}

const imageDirectory = readArgument("image-directory", "character-images");
// Keep this relative so images also work when the app is deployed under a GitHub Pages project path.
const imageBaseUrl = readArgument("image-base-url", "./character-images").replace(/\/$/, "");
const absoluteImageDirectory = resolve(projectRoot, imageDirectory);
const entries = await readdir(absoluteImageDirectory, { withFileTypes: true });
const knownIds = new Map(CHARACTER_CATALOG.map((character) => [encodeURIComponent(String(character.id)), String(character.id)]));
const manifest = {};
const unmatchedFiles = [];

for (const entry of entries) {
  if (!entry.isFile()) continue;
  const extension = extname(entry.name).toLowerCase();
  if (!supportedExtensions.has(extension)) continue;
  const encodedId = entry.name.slice(0, -extension.length);
  const characterId = knownIds.get(encodedId);
  if (!characterId) {
    unmatchedFiles.push(entry.name);
    continue;
  }
  manifest[characterId] = `${imageBaseUrl}/${encodeURIComponent(entry.name)}`;
}

const outputPath = resolve(projectRoot, "src/data/character-image-manifest.js");
const source = [
  "// Generated by scripts/build-character-image-manifest.mjs. Do not edit manually.",
  `export const CHARACTER_IMAGE_BY_ID = Object.freeze(${JSON.stringify(manifest, null, 2)});`,
  "",
].join("\n");
await writeFile(outputPath, source, "utf8");

console.log(`Mapped ${Object.keys(manifest).length.toLocaleString("ja-JP")} character images.`);
if (unmatchedFiles.length) {
  console.warn(`Skipped ${unmatchedFiles.length.toLocaleString("ja-JP")} files with no matching encoded character ID.`);
}
